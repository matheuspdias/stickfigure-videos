# VA de R$ 600 (valor ilustrativo, redondo)
va = 600
print("por dia", va / 30)            # 20
basico = 250                          # arroz, feijão, óleo, café, macarrão, leite (compra do mês, estimativa)
resto = va - basico
print("resto", resto, "por semana", resto / 4)  # 350 -> 87,5 (narração: uns 87)
# Regra: VA só para gêneros alimentícios (Lei 14.442/2022, PAT; decreto em vigor desde 10/02/2026). Limpeza/higiene fora.
